#!/usr/bin/env bash
# Creates /srv/kezjegy/.env and /srv/kezjegy/.env.db with fresh random secrets (chmod 600) when they do not exist
# yet, and adds any generated key that is missing. Never prints a value. Also creates the backup passphrase.
# Safe to run repeatedly: existing values are never changed (only moved between the two files, see below).
#
# QA kör 3 – secrets split:
#   .env     → API + worker (app settings, app keys, DATABASE_URL of the least-privilege role kezjegy_app)
#   .env.db  → ONLY kezjegy-db and the one-shot kezjegy-migrate: POSTGRES_PASSWORD, MIGRATION_DATABASE_URL (owner),
#              KEZJEGY_APP_DB_PASSWORD. A superuser credential never reaches the API or the worker.
# An older .env that still holds those keys is copied to _regi/ first, then the keys move to .env.db.
set -euo pipefail
umask 077
ENV=/srv/kezjegy/.env
ENVDB=/srv/kezjegy/.env.db
cd /srv/kezjegy
mkdir -p _regi

python3 - "$ENV" "$ENVDB" <<'PY'
import base64, os, secrets, shutil, sys, time
path, dbpath = sys.argv[1], sys.argv[2]
OWNER_KEYS = ("POSTGRES_PASSWORD", "MIGRATION_DATABASE_URL", "KEZJEGY_APP_DB_PASSWORD")

def read(p):
    return open(p).read().splitlines() if os.path.exists(p) else []

def kv(lines):
    return {l.split("=", 1)[0]: l.split("=", 1)[1] for l in lines if "=" in l and not l.lstrip().startswith("#")}

def write(p, lines):
    fd = os.open(p, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write("\n".join(lines) + "\n")
    os.chmod(p, 0o600)

b64 = lambda: base64.b64encode(secrets.token_bytes(32)).decode()
lines = read(path) or [
    "# Kézjegy – /srv/kezjegy/.env (SPEC §13). Generated by deploy/gen-env.sh. chmod 600. Never print or copy.",
    "# Change keys only with kezjegy_kulcsok.ps1 (from the owner's PC). The database owner's secrets are in .env.db.",
]
dblines = read(dbpath) or [
    "# Kezjegy - /srv/kezjegy/.env.db: database owner secrets, ONLY for kezjegy-db and kezjegy-migrate. chmod 600.",
]
env, db = kv(lines), kv(dblines)
added, moved = [], []

# 1) move the owner secrets out of .env (backup first)
if any(k in env for k in OWNER_KEYS):
    ts = time.strftime("%Y%m%d_%H%M%S")
    shutil.copy2(path, f"/srv/kezjegy/_regi/env_elotte_szetvalasztas_{ts}")
    keep = []
    for l in lines:
        k = l.split("=", 1)[0] if "=" in l and not l.lstrip().startswith("#") else None
        if k in OWNER_KEYS:
            if k not in db:
                dblines.append(l)
                db[k] = l.split("=", 1)[1]
            moved.append(k)
        else:
            keep.append(l)
    lines = keep
    env = kv(lines)

# 2) database secrets
if "POSTGRES_PASSWORD" not in db:
    if "DATABASE_URL" in env and "kezjegy:" in env["DATABASE_URL"]:
        raise SystemExit("A .env-ben van tulajdonosi DATABASE_URL, de POSTGRES_PASSWORD nincs: kézzel kell pótolni.")
    db["POSTGRES_PASSWORD"] = secrets.token_hex(24)
    dblines.append(f"POSTGRES_PASSWORD={db['POSTGRES_PASSWORD']}")
    added.append("POSTGRES_PASSWORD")
if "KEZJEGY_APP_DB_PASSWORD" not in db:
    db["KEZJEGY_APP_DB_PASSWORD"] = secrets.token_hex(24)
    dblines.append(f"KEZJEGY_APP_DB_PASSWORD={db['KEZJEGY_APP_DB_PASSWORD']}")
    added.append("KEZJEGY_APP_DB_PASSWORD")
owner_url = f"postgres://kezjegy:{db['POSTGRES_PASSWORD'].strip()}@kezjegy-db:5432/kezjegy"
if "MIGRATION_DATABASE_URL" not in db:
    # an old first-deploy .env had the owner URL as DATABASE_URL
    cur = env.get("DATABASE_URL", "")
    db["MIGRATION_DATABASE_URL"] = cur if cur.startswith("postgres://kezjegy:") else owner_url
    dblines.append(f"MIGRATION_DATABASE_URL={db['MIGRATION_DATABASE_URL']}")
    added.append("MIGRATION_DATABASE_URL")

# 3) the API/worker always use the least-privilege role (db-roles.sh creates it before the API starts)
app_url = f"postgres://kezjegy_app:{db['KEZJEGY_APP_DB_PASSWORD'].strip()}@kezjegy-db:5432/kezjegy"
if env.get("DATABASE_URL", "").startswith("postgres://kezjegy:") or "DATABASE_URL" not in env:
    if "DATABASE_URL" in env:
        lines = [l for l in lines if not l.startswith("DATABASE_URL=")]
    lines.append("# API + worker: least-privilege role kezjegy_app (deploy/db-roles.sh)")
    lines.append(f"DATABASE_URL={app_url}")
    env["DATABASE_URL"] = app_url
    added.append("DATABASE_URL(kezjegy_app)")

# 4) app secrets and defaults
generated = {
    "JWT_SECRET": b64(), "CODE_HMAC_SECRET": b64(), "FILE_LINK_SECRET": b64(), "AUDIT_IP_SALT": b64(),
    "FILE_ENC_KEY": b64(), "APP_DATA_KEY": b64(), "NAV_CRED_KEY": b64(),
    "SIMPLEPAY_DEMO_SECRET": secrets.token_hex(24),
}
defaults = [
    ("APP_ENV", "demo"), ("NODE_ENV", "production"), ("PORT", "8080"), ("LOG_LEVEL", "info"), ("APP_VERSION", "0.1.0-demo"),
    ("APP_PUBLIC_URL", "https://app.45-94-65-74.sslip.io"),
    ("PANEL_PUBLIC_URL", "https://konyvelo.45-94-65-74.sslip.io"),
    ("API_PUBLIC_URL", "https://api.45-94-65-74.sslip.io"),
    ("FILE_ENC_KEY_ID", "1"), ("STAFF_TOTP_REQUIRED", "true"),
    ("SMTP_PORT", "587"),
    ("SIMPLEPAY_MODE", "demo"), ("SIMPLEPAY_RECURRING_TIMES", "12"), ("SIMPLEPAY_TOKEN_VALID_MONTHS", "12"),
    ("PLAN_PRICE_HUF", "20000"), ("INVOICE_MODE", "demo"),
    ("NAV_MODE", "demo"), ("NAV_SOFTWARE_ID", "HU00000000KEZJEGY1"), ("NAV_SOFTWARE_VERSION", "1.0.0"), ("NAV_SYNC_HOUR", "5"),
    ("PUSH_MODE", "demo"), ("TRUST_PROXY_HOPS", "1"),
]
for k, v in list(generated.items()) + defaults:
    if k not in env:
        lines.append(f"{k}={v}")
        env[k] = v
        added.append(k)

write(path, lines)
write(dbpath, dblines)
msg = []
if moved: msg.append("moved to .env.db: " + ", ".join(moved))
if added: msg.append("added " + ", ".join(added))
print("env: " + ("; ".join(msg) if msg else "nothing to change"))
PY
chmod 600 "$ENV" "$ENVDB"

# passphrase for the gpg-encrypted nightly DB dumps (backup.sh)
if [ ! -s /srv/kezjegy/.backup_pass ]; then
  python3 -c 'import secrets; print(secrets.token_urlsafe(36))' > /srv/kezjegy/.backup_pass
  chmod 600 /srv/kezjegy/.backup_pass
  echo "backup passphrase: created"
fi
