#!/usr/bin/env node
// One-off generator: copies the pen-stroke paths from the approved design (app_v2/kozos.js, kezjegy_utak.js)
// into src/ui/kezvonas.ts. Re-run only if the design's strokes change.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, '../../../dizajn/C2_modern/app_v2');
const kozos = readFileSync(resolve(app, 'kozos.js'), 'utf8');
const utak = readFileSync(resolve(app, 'kezjegy_utak.js'), 'utf8');
const ikon = kozos.match(/ikon:\s*"([^"]+)"/)[1];
const szojegy = kozos.match(/szojegy:\s*"([^"]+)"/)[1];
const alairas = utak.match(/alairas:\s*"([^"]+)"/)[1];
const out = `// GENERATED by scripts/gen-paths.mjs from dizajn/C2_modern/app_v2 (kozos.js, kezjegy_utak.js). Do not edit.
// Pen strokes of the approved identity. The accountant's real signature comes from the API
// (accountant.signatureSvgPath); DEMO_SIGNATURE is the design's placeholder, used only by the local mock.
export const PEN_STROKE_ICON = ${JSON.stringify(ikon)}; // viewBox 0 0 120 120
export const PEN_STROKE_WORDMARK = ${JSON.stringify(szojegy)}; // viewBox 0 0 220 26
export const DEMO_SIGNATURE = ${JSON.stringify(alairas)}; // viewBox 0 0 210 78
`;
writeFileSync(resolve(here, '../src/ui/kezvonas.ts'), out);
console.log('paths ->', ikon.length, szojegy.length, alairas.length);
